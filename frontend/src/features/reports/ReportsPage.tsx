function Previews() {
  const org = useOrganization().organization!;
  const [type, setType] = useState<PreviewType>('INVOICE_REGISTER');
  const [parameters, setParameters] = useState<ReportParameters>(
    defaultParameters(type, org.timezone),
  );
  const [cursors, setCursors] = useState<(string | undefined)[]>([undefined]);
  const [limit, setLimit] = useState<25 | 50 | 100>(25);
  const preview = usePreview(
    org.id,
    type,
    parameters,
    org.baseCurrency,
    org.timezone,
    limit,
    cursors.at(-1),
  );
  const data = !preview.isFetching && !preview.isError ? preview.data : undefined;
  const changeType = (next: PreviewType) => {
    setType(next);
    setParameters(defaultParameters(next, org.timezone));
    setCursors([undefined]);
  };
  const cell = (row: PreviewRow, key: string) => {
    const value = (row as unknown as Record<string, unknown>)[key];
    return ['total', 'paid', 'balance', 'amount'].includes(key) && typeof value === 'string'
      ? formatMoney(value, org.baseCurrency)
      : typeof value === 'boolean'
        ? value
          ? 'Yes'
          : 'No'
        : value === null || value === undefined
          ? '—'
          : String(value);
  };
  return (
    <section className={styles.panel} aria-label="Report preview">
      <h2>Report preview</h2>
      <div className={styles.controls}>
        <label>
          Preview report type
          <select value={type} onChange={(event) => changeType(event.target.value as PreviewType)}>
            {Object.keys(columns).map((value) => (
              <option key={value} value={value}>
                {reportLabels[value as PreviewType]}
              </option>
            ))}
          </select>
        </label>
        <label>
          Preview rows per page
          <select
            value={limit}
            onChange={(event) => {
              setLimit(Number(event.target.value) as 25 | 50 | 100);
              setCursors([undefined]);
            }}
          >
            {[25, 50, 100].map((value) => (
              <option key={value}>{value}</option>
            ))}
          </select>
        </label>
        <button
          className={styles.secondary}
          disabled={preview.isFetching}
          onClick={() => {
            void preview.refetch();
          }}
        >
          Refresh preview
        </button>
      </div>
      <ReportFilters
        key={type}
        type={type}
        button="Apply preview filters"
        apply={(values) => {
          setParameters(values);
          setCursors([undefined]);
        }}
      />
      <p className={styles.note}>
        Current-state page only; no aggregate is derived from these rows. Registers sort by ID
        ascending. Receivables uses the backend's fixed aging buckets. {org.baseCurrency} ·{' '}
        {org.timezone}
      </p>
      {preview.isPending || preview.isFetching ? (
        <Loading />
      ) : preview.isError ? (
        <ReadError
          error={preview.error}
          retry={() => {
            void preview.refetch();
          }}
          restart={() => setCursors([undefined])}
        />
      ) : (
        data && (
          <>
            {!data.data.length && <p>No report rows in this selection.</p>}
            <div
              className={styles.tableWrap}
              role="region"
              tabIndex={0}
              aria-label="Scrollable report preview"
            >
              <table>
                <caption>
                  {reportLabels[type]} preview ({data.meta.currency as string})
                </caption>
                <thead>
                  <tr>
                    {columns[type].map((column) => (
                      <th scope="col" key={column}>
                        {columnLabels[column] ?? column}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {data.data.map((row, index) => (
                    <tr key={'id' in row ? row.id : 'bucket' in row ? row.bucket : index}>
                      {columns[type].map((column) => (
                        <td key={column}>{cell(row, column)}</td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <Pagination
              page={cursors.length}
              hasPrevious={cursors.length > 1}
              hasNext={data.meta.hasMore}
              previous={() => setCursors((old) => old.slice(0, -1))}
              next={() => setCursors((old) => [...old, data.meta.nextCursor!])}
            />
          </>
        )
      )}
    </section>
  );
}
