import styles from './Reports.module.css';
export function ReportsPage() {
  const context = useOrganization();
  return (
    <ReportBoundary permission="reports">
      {context.organization && <Reports key={context.organization.id} />}
    </ReportBoundary>
  );
}
function Reports() {
  const context = useOrganization();
  const [tab, setTab] = useState(context.hasPermission('report.export') ? 'exports' : 'preview');
  return (
    <div className={styles.page}>
      <header>
        <h1>Reports</h1>
        <p>Server-generated current-state registers and financial CSV exports.</p>
      </header>
      <div className={styles.actions}>
        {context.hasPermission('report.read') && (
          <button
            className={styles.secondary}
            aria-pressed={tab === 'preview'}
            onClick={() => setTab('preview')}
          >
            Preview reports
          </button>
        )}
        {context.hasPermission('report.export') && (
          <button
            className={styles.secondary}
            aria-pressed={tab === 'exports'}
            onClick={() => setTab('exports')}
          >
            CSV exports
          </button>
        )}
      </div>
      <p className={styles.note}>
        Simplified cash-basis management reporting, not a GAAP/IFRS statement or frozen historical
        reconstruction. CSV contents are generated by the server, not from the visible page. Refresh
        status manually; generation requires the report worker.
      </p>
      {tab === 'exports' ? <Exports /> : <Previews />}
    </div>
  );
}
function Exports() {
  const org = useOrganization().organization!;
  const [params, setParams] = useSearchParams();
  const [type, setType] = useState<ReportType>('INVOICE_REGISTER');
  const [filters, setFilters] = useState({ ...defaultExportFilters });
  const [cursors, setCursors] = useState<(string | undefined)[]>([undefined]);
  const command = useCreateExport(org.id);
  const list = useExports(org.id, filters, cursors.at(-1));
  const downloader = useCsvDownload(org.id);
  const data = !list.isFetching && !list.isError ? list.data : undefined;
  const selected = params.get('exportId') ?? '';
  function change(values: Partial<ExportFilters>) {
    setFilters((old) => ({ ...old, ...values }));
    setCursors([undefined]);
  }
  return (
    <>
      <section className={styles.panel} aria-label="Report creation">
        <h2>Request CSV export</h2>
        <label>
          Export report type
          <select
            disabled={command.isPending || !!command.attempt}
            value={type}
            onChange={(event) => setType(event.target.value as ReportType)}
          >
            {reportTypes.map((value) => (
              <option key={value} value={value}>
                {reportLabels[value]}
              </option>
            ))}
          </select>
        </label>
        <ReportFilters
          key={type}
          type={type}
          disabled={command.isPending || !!command.attempt}
          button={command.isPending ? 'Requesting export…' : 'Request CSV export'}
          apply={(parameters) => {
            void command.send({ reportType: type, format: 'CSV', parameters }).then((row) => {
              if (row) {
                setCursors([undefined]);
                setParams({ exportId: row.id });
              }
            });
          }}
        />
        {command.error && (
          <p role="alert" className={styles.error}>
            {command.error}
          </p>
        )}
        {command.attempt && !command.isPending && (
          <button
            onClick={() => {
              void command.send().then((row) => {
                if (row) setParams({ exportId: row.id });
              });
            }}
          >
            Retry same export request
          </button>
        )}
        <p className={styles.note}>
          Generation is asynchronous. Files are limited to 10,000 rows and 10 MiB. Unconfirmed
          requests retain the original key; a browser reload clears the attempt, so inspect history
          before requesting again.
        </p>
      </section>
      {selected &&
        (uuid.safeParse(selected).success ? (
          <ExportDetail key={selected} id={selected} downloader={downloader} />
        ) : (
          <p role="alert">Enter a valid export identifier.</p>
        ))}
      <section className={styles.panel} aria-label="Export history">
        <h2>Export history</h2>
        <div className={styles.controls}>
          <label>
            Export type filter
            <select
              value={filters.reportType}
              onChange={(event) =>
                change({ reportType: event.target.value as ExportFilters['reportType'] })
              }
            >
              <option value="">All report types</option>
              {reportTypes.map((value) => (
                <option key={value} value={value}>
                  {reportLabels[value]}
                </option>
              ))}
            </select>
          </label>
          <label>
            Export status filter
            <select
              value={filters.status}
              onChange={(event) =>
                change({ status: event.target.value as ExportFilters['status'] })
              }
            >
              <option value="">All states</option>
              {exportStatuses.map((status) => (
                <option key={status}>{status}</option>
              ))}
            </select>
          </label>
          <label>
            Exports per page
            <select
              value={filters.limit}
              onChange={(event) =>
                change({ limit: Number(event.target.value) as ExportFilters['limit'] })
              }
            >
              {[25, 50, 100].map((limit) => (
                <option key={limit}>{limit}</option>
              ))}
            </select>
          </label>
          <button
            className={styles.secondary}
            disabled={list.isFetching}
            onClick={() => {
              void list.refetch();
            }}
          >
            Refresh export history
          </button>
        </div>
        {list.isPending || list.isFetching ? (
          <Loading />
        ) : list.isError ? (
          <ReadError
            error={list.error}
            retry={() => {
              void list.refetch();
            }}
            restart={() => setCursors([undefined])}
          />
        ) : (
          data && (
            <>
              {!data.data.length && <p>No exports available yet.</p>}
              <ul className={styles.cards} aria-label="Report exports">
                {data.data.map((row) => (
                  <li className={styles.card} key={row.id}>
                    <ExportFacts row={row} />
                    <div className={styles.actions}>
                      <button
                        className={styles.secondary}
                        aria-label={`Inspect export ${row.id}`}
                        onClick={() => setParams({ exportId: row.id })}
                      >
                        Inspect status
                      </button>
                      {row.status === 'READY' && (
                        <button
                          disabled={!!downloader.pending}
                          aria-label={`Download CSV ${row.id}`}
                          onClick={() => {
                            void downloader.download(row.id);
                          }}
                        >
                          Download CSV
                        </button>
                      )}
                    </div>
                  </li>
                ))}
              </ul>
              <Pagination
                page={cursors.length}
                hasPrevious={cursors.length > 1}
                hasNext={data.meta.hasMore}
                previous={() => setCursors((old) => old.slice(0, -1))}
                next={() => setCursors((old) => [...old, data.meta.nextCursor!])}
              />
            </>
          )
        )}
      </section>
      {downloader.pending && <p role="status">Downloading CSV…</p>}
      {downloader.error && (
        <p role="alert" className={styles.error}>
          {downloader.error}
        </p>
      )}
    </>
  );
}
function ExportFacts({ row }: { row: ReportExport }) {
  const org = useOrganization().organization!;
  return (
    <>
      <h3>{reportLabels[row.reportType]}</h3>
      <p className={styles.status} data-state={row.status}>
        Status: {row.status}
      </p>
      <dl className={styles.facts}>
        <div>
          <dt>Export ID</dt>
          <dd>{row.id}</dd>
        </div>
        <div>
          <dt>Requested</dt>
          <dd>
            <time dateTime={row.createdAt} title={row.createdAt}>
              {notificationTimestamp(row.createdAt, org.timezone)}
            </time>{' '}
            ({org.timezone})
          </dd>
        </div>
        <div>
          <dt>Rows</dt>
          <dd>{row.rowCount ?? 'Not generated'}</dd>
        </div>
        {row.completedAt && (
          <div>
            <dt>Completed</dt>
            <dd>
              <time dateTime={row.completedAt}>
                {notificationTimestamp(row.completedAt, org.timezone)}
              </time>
            </dd>
          </div>
        )}
        {row.expiresAt && (
          <div>
            <dt>Expires</dt>
            <dd>
              <time dateTime={row.expiresAt}>
                {notificationTimestamp(row.expiresAt, org.timezone)}
              </time>
            </dd>
          </div>
        )}
        {Object.entries(row.parameters).map(([field, value]) => (
          <div key={field}>
            <dt>{parameterLabels[field] ?? field}</dt>
            <dd>{value}</dd>
          </div>
        ))}
      </dl>
      {row.status === 'FAILED' && (
        <p>
          {row.errorCode === 'REPORT_TOO_LARGE'
            ? 'Report exceeds the supported row/file limit. Choose narrower parameters.'
            : row.errorCode === 'REPORT_ACCESS_REVOKED'
              ? 'Requester access was revoked.'
              : 'Report generation failed. Review its parameters before a new request.'}
        </p>
      )}
    </>
  );
}
function ExportDetail({
  id,
  downloader,
}: {
  id: string;
  downloader: ReturnType<typeof useCsvDownload>;
}) {
  const org = useOrganization().organization!;
  const detail = useExportDetail(org.id, id, true);
  return (
    <section className={styles.panel} aria-label="Export status">
      <h2>Export status</h2>
      <button
        className={styles.secondary}
        disabled={detail.isFetching}
        onClick={() => {
          void detail.refetch();
        }}
      >
        Refresh export status
      </button>
      {detail.isPending || detail.isFetching ? (
        <Loading />
      ) : detail.isError ? (
        <ReadError
          error={detail.error}
          retry={() => {
            void detail.refetch();
          }}
        />
      ) : (
        detail.data && (
          <>
            <ExportFacts row={detail.data} />
            {detail.data.status === 'READY' && (
              <button
                disabled={!!downloader.pending}
                onClick={() => {
                  void downloader.download(id);
                }}
              >
                Download selected CSV
              </button>
            )}
          </>
        )
      )}
    </section>
  );
}
